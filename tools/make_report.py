"""
Build results/RESULTS.md from out/<clip_id>/hands.jsonl (and summary.json when present).

Only numbers are read and written. No video, frame or image is touched.

    python tools/make_report.py                 # reads out/, writes results/RESULTS.md
    python tools/make_report.py --out out --dest results/RESULTS.md
"""
import argparse
import json
import statistics
from pathlib import Path


def analyse(hands_path, summary_path=None):
    rows = [json.loads(line) for line in open(hands_path, encoding="utf-8")]
    n = len(rows)
    times = [r["t_ms"] for r in rows]
    spacing = statistics.median(b - a for a, b in zip(times, times[1:])) if n > 1 else 0

    with_hands = sum(1 for r in rows if r["hands"])
    two_hands = sum(1 for r in rows if len(r["hands"]) == 2)
    unknown_frames = sum(1 for r in rows if any(h["side"] == "unknown" for h in r["hands"]))
    scores = [h["handedness_score"] for r in rows for h in r["hands"] if h["handedness_score"] is not None]

    # plausibility proxy: in first-person footage the worker's left hand is normally left of the right hand
    both, left_of_right = 0, 0
    for r in rows:
        ids = {h["hand_id"]: h for h in r["hands"]}
        if "L" in ids and "R" in ids:
            both += 1
            if ids["L"]["kp2d_px"][0][0] < ids["R"]["kp2d_px"][0][0]:
                left_of_right += 1

    # stretches of processed frames in which no hand was found
    gaps, run_start, prev_t = [], None, None
    for r in rows:
        if not r["hands"]:
            if run_start is None:
                run_start = r["t_ms"]
            prev_t = r["t_ms"]
        elif run_start is not None:
            gaps.append(prev_t - run_start + spacing)
            run_start = None
    if run_start is not None:
        gaps.append(prev_t - run_start + spacing)

    pts = outside = 0
    for r in rows:
        w, h = r["frame_width"], r["frame_height"]
        for hand in r["hands"]:
            for x, y in hand["kp2d_px"]:
                pts += 1
                if x < 0 or y < 0 or x > w or y > h:
                    outside += 1

    summary = {}
    if summary_path and Path(summary_path).exists():
        summary = json.load(open(summary_path, encoding="utf-8"))
    cfg = summary.get("run_config", {})

    return {
        "clip": rows[0]["clip_id"],
        "resolution": f'{rows[0]["frame_width"]}x{rows[0]["frame_height"]}',
        "frames": n,
        "seconds": round(times[-1] / 1000, 1),
        "with_hands": 100 * with_hands / n,
        "two_hands": 100 * two_hands / n,
        "mean_score": statistics.mean(scores) if scores else float("nan"),
        "unknown_frames": 100 * unknown_frames / n,
        "lr_consistency": (100 * left_of_right / both) if both else None,
        "lr_frames": both,
        "gap_count": len(gaps),
        "longest_gap_s": (max(gaps) / 1000) if gaps else 0.0,
        "outside_pts": 100 * outside / pts if pts else 0.0,
        "fps": summary.get("processing_fps"),
        "swap_lr": cfg.get("swap_lr"),
        "step": cfg.get("step"),
    }


def fmt(v, spec="{:.1f}", none="n/a"):
    return none if v is None else spec.format(v)


def build(stats):
    L = []
    L.append("# Results: hand detection baseline (Function 1)\n")
    L.append("Generated by `python tools/make_report.py` from `out/<clip_id>/hands.jsonl`. "
             "Numbers only: no footage, frames or screenshots are included.\n")
    L.append("## Per-clip numbers\n")
    L.append("| Clip | Size | Frames processed | Frames with a hand | Frames with two hands | "
             "Mean handedness score | Frames with an `unknown` side | "
             "Left-hand-left-of-right-hand | Hand-free stretches (count / longest) |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for s in stats:
        lr = "n/a" if s["lr_consistency"] is None else f'{s["lr_consistency"]:.1f}% of {s["lr_frames"]} frames'
        L.append(f'| `{s["clip"]}` | {s["resolution"]} | {s["frames"]} ({s["seconds"]} s) | '
                 f'{s["with_hands"]:.1f}% | {s["two_hands"]:.1f}% | {fmt(s["mean_score"], "{:.3f}")} | '
                 f'{s["unknown_frames"]:.1f}% | {lr} | {s["gap_count"]} / {s["longest_gap_s"]:.1f} s |')
    L.append("")
    L.append("## Run settings\n")
    L.append("| Clip | Frame step | Left/right swap | Speed (frames/s) | Frames outside the image |")
    L.append("|---|---|---|---|---|")
    for s in stats:
        L.append(f'| `{s["clip"]}` | every {fmt(s["step"], "{}")} | {fmt(s["swap_lr"], "{}")} | '
                 f'{fmt(s["fps"], "{:.1f}")} | {s["outside_pts"]:.2f}% of keypoints |')
    L.append("")
    L.append("Speed depends on the machine that ran the batch. Re-run on the target laptop to record its own speed.\n")
    L.append("## What the columns mean\n")
    L.append("- **Frames with a hand**: share of processed frames in which MediaPipe returned at least one hand. "
             "This is coverage, not accuracy.")
    L.append("- **Mean handedness score**: MediaPipe's own confidence in its left/right label, averaged over all detected hands.")
    L.append("- **`unknown` side**: frames where both hands received the same label. The lower-scoring hand is kept "
             "but marked `unknown` instead of being discarded.")
    L.append("- **Left-hand-left-of-right-hand**: in frames with both an `L` and an `R` hand, how often the `L` wrist is "
             "left of the `R` wrist in the image. This is a plausibility check for the left/right labels, "
             "not a ground-truth measurement.")
    L.append("- **Hand-free stretches**: runs of consecutive processed frames with no hand found.\n")
    L.append("## What this report does NOT measure\n")
    L.append("- Whether the 21 points sit on the correct joints. That needs hand-labelled frames, which are not made yet.")
    L.append("- Whether any single left/right label is correct. Only the plausibility check above is available.")
    L.append("- Identity stability, jitter or recovery after a hand re-enters the view. There is no tracking step yet.\n")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="out", help="folder that holds one sub-folder per clip")
    ap.add_argument("--dest", default="results/RESULTS.md")
    args = ap.parse_args()
    stats = []
    for d in sorted(p for p in Path(args.out).iterdir() if p.is_dir()):
        h = d / "hands.jsonl"
        if h.exists():
            stats.append(analyse(h, d / "summary.json"))
    if not stats:
        raise SystemExit(f"no hands.jsonl found under {args.out}/")
    dest = Path(args.dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(build(stats), encoding="utf-8")
    print(f"wrote {dest} ({len(stats)} clips)")


if __name__ == "__main__":
    main()
